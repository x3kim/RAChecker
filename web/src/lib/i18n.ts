const DICTS: Record<Lang, Dict> = { de: DE, en: EN };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}

interface I18nValue { lang: Lang; setLang: (l: Lang) => void; t: (key: string, vars?: Record<string, string | number>) => string }
const I18nCtx = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(loadLang);
  useEffect(() => { document.documentElement.lang = lang; _lang = lang; }, [lang]);
  const setLang = useCallback((l: Lang) => { localStorage.setItem(KEY, l); _lang = l; setLangState(l); }, []);
  const t = useCallback((key: string, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
  return createElement(I18nCtx.Provider, { value: { lang, setLang, t } }, children);
}

export function useI18n(): I18nValue {
  const v = useContext(I18nCtx);
  if (!v) throw new Error('useI18n must be used within I18nProvider');
  return v;
}
